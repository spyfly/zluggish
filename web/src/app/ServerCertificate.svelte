<script lang="ts">
  import { onMount } from 'svelte';
  import Fingerprint from '../components/Fingerprint.svelte';
  import type { TlsStatus } from './tls';

  type Confirmation = {
    title: string;
    detail: string;
    label: string;
    destructive: boolean;
    confirm: () => Promise<void>;
  };

  let {
    api,
    busy,
    confirm,
    done,
    onstatus,
  }: {
    api: (url: string, method?: string, data?: { operation: string }) => Promise<TlsStatus>;
    busy: boolean;
    /** Asks the administrator before the action runs. */
    confirm: (confirmation: Confirmation) => void;
    /** Reports the outcome in the page notice. */
    done: (message: string) => void;
    /** Hears the certificate status whenever it loads or changes. */
    onstatus?: ((status: TlsStatus) => void) | undefined;
  } = $props();

  let status = $state<TlsStatus | null>(null);
  let failure = $state('');

  const sources = {
    managed: 'Generated by this server',
    legacy: 'Shared Zwift certificate',
    custom: 'Certificate files from the configuration',
    disabled: 'None: the Zwift API serves plain HTTP',
  };

  const day = (iso: string) =>
    new Date(iso).toLocaleDateString([], { year: 'numeric', month: 'short', day: 'numeric' });

  /** How long ago, or how long from now, in the largest whole unit. */
  function relative(iso: string) {
    const days = Math.round((Date.parse(iso) - Date.now()) / 86_400_000);
    const format = new Intl.RelativeTimeFormat([], { numeric: 'auto' });

    if (Math.abs(days) >= 365) return format.format(Math.trunc(days / 365), 'year');

    if (Math.abs(days) >= 60) return format.format(Math.trunc(days / 30), 'month');

    return format.format(days, 'day');
  }

  const expiresSoon = $derived(
    !!status?.certificate && Date.parse(status.certificate.notAfter) - Date.now() < 90 * 86_400_000,
  );

  onMount(async () => {
    try {
      status = await api('/api/tls');
      onstatus?.(status);
    } catch (error) {
      failure = error instanceof Error ? error.message : 'The certificate could not be loaded.';
    }
  });

  function rotate() {
    const legacy = status?.mode === 'legacy';
    const operation = crypto.randomUUID();

    confirm({
      title: legacy ? 'Switch to a server certificate?' : 'Rotate the server certificate?',
      detail: `The server makes a new key and certificate and uses them at once. Every computer stops connecting until its rider runs the setup again from Install.${legacy ? ' Android devices patched with ZofflineObb trust only the shared certificate and stop connecting.' : ''}`,
      label: legacy ? 'Generate certificate' : 'Rotate certificate',
      destructive: true,
      confirm: async () => {
        status = await api('/api/manage/server/certificate', 'POST', { operation });
        onstatus?.(status);
        done(
          legacy
            ? 'Generated a server certificate. Ask every rider to run the setup from Install.'
            : 'Rotated the certificate. Ask every rider to run the setup from Install again.',
        );
      },
    });
  }
</script>

<section class="panel" class:unsafe={status?.mode === 'legacy'} aria-labelledby="certificate-title">
  <h2 id="certificate-title">Zwift certificate</h2>
  {#if failure}<p class="failed" role="alert">{failure}</p>{/if}
  {#if status}
    {#if status.mode === 'legacy'}
      <p class="warning" role="alert">
        The private key of the shared Zwift certificate is public. Anyone on your network can read and change what Zwift
        sends, passwords included. Generate a certificate for this server, then ask every rider to run the setup from
        Install.
      </p>
    {/if}

    <dl class="facts">
      <div>
        <dt>Source</dt>
        <dd>{sources[status.mode]}</dd>
      </div>
      {#if status.certificate}
        <div>
          <dt>Created</dt>
          <dd>
            <time datetime={status.certificate.notBefore}>{day(status.certificate.notBefore)}</time>
            <span class="muted">({relative(status.certificate.notBefore)})</span>
          </dd>
        </div>
        <div>
          <dt>Expires</dt>
          <dd class:failed={expiresSoon}>
            <time datetime={status.certificate.notAfter}>{day(status.certificate.notAfter)}</time>
            <span class:muted={!expiresSoon}>({relative(status.certificate.notAfter)})</span>
          </dd>
        </div>
        <div>
          <dt>Key</dt>
          <dd>{status.certificate.key}</dd>
        </div>
      {/if}
    </dl>

    {#if status.certificate}
      <Fingerprint label="SHA-256 fingerprint" value={status.certificate.fingerprint256} />
    {/if}

    {#if status.mode === 'managed' || status.mode === 'legacy'}
      <p class="muted">
        {status.mode === 'managed'
          ? `New certificates are valid for ${status.lifetimeYears} ${status.lifetimeYears === 1 ? 'year' : 'years'}. Rotate the certificate if its key may have leaked, or before it expires.`
          : 'Until you switch, riders can still download setup for the shared certificate from Install, behind a warning. The server log records each download. The new certificate replaces the shared one for every client at once.'}
      </p>
      <button class={status.mode === 'legacy' ? 'primary' : 'danger'} disabled={busy} onclick={rotate}
        >{status.mode === 'legacy' ? 'Generate certificate' : 'Rotate certificate'}</button
      >
    {:else if status.mode === 'custom'}
      <p class="muted">
        To change it, replace the files that tls.certFile and tls.keyFile name, then restart the server.
      </p>
    {/if}
  {:else if !failure}
    <p role="status">Loading…</p>
  {/if}
</section>

